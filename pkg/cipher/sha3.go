package cipher

// SHA-3 for s390x, with no third-party dependencies.
//
// The dependency question first, because it drives the design.
//
// Go put SHA-3 in the standard library as crypto/sha3 in Go 1.24. The target
// toolchain here is go1.23.2, where `go doc crypto/sha3` reports
// "package crypto/sha3 is not in std". The obvious alternative,
// golang.org/x/crypto/sha3, would add the project's first third-party require
// to a go.mod that currently has none, which is a promise the README makes.
//
// So this file carries two implementations:
//
//  1. A pure-Go Keccak-f[1600] permutation and the four standard SHA-3 sponge
//     configurations (224/256/384/512). It is correct and portable, it runs
//     everywhere, and it is the reference the hardware path is checked against.
//
//  2. An AF_ALG path that submits the message to the kernel crypto API. On
//     s390x the kernel's sha3-256 driver is "sha3-256-s390", which lowers to
//     KIMD function codes 32..35 — the real CPACF hardware. This is how ZCrypt
//     measures SHA-3 throughput on hardware without linking a library, and it
//     is also how it proves the hardware driver agrees with the software
//     implementation bit for bit.
//
// The AF_ALG path is deliberately optional: it is only attempted when the host
// reports the driver in /proc/crypto and the socket family is available. Every
// test that depends on it skips cleanly when it is not, so the suite still
// passes on amd64 CI runners and inside containers without AF_ALG.

