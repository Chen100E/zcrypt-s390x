// VectorInput materialises the message bytes for a vector.
func (v SHA3Vector) VectorInput() []byte {
	if v.Repeat > 0 {
		out := make([]byte, v.Repeat)
		for i := range out {
			out[i] = v.RepeatByte
		}
		return out
	}
	if v.Input == "" {
		return nil
	}
	out := make([]byte, len(v.Input)/2)
	for i := 0; i < len(out); i++ {
		out[i] = hexNibble(v.Input[2*i])<<4 | hexNibble(v.Input[2*i+1])
	}
	return out
}

func hexNibble(c byte) byte {
	switch {
	case c >= '0' && c <= '9':
		return c - '0'
	case c >= 'a' && c <= 'f':
		return c - 'a' + 10
	case c >= 'A' && c <= 'F':
		return c - 'A' + 10
	}
	return 0
}

// VerifySHA3Vectors checks every known-answer case against the pure-Go
// implementation and returns the number that passed.
func VerifySHA3Vectors() (int, error) {
	passed := 0
	for _, v := range NISTSHA3Vectors {
		got := SHA3Sum(v.Variant, v.VectorInput())
		if hexEncode(got) != v.Digest {
			return passed, fmt.Errorf("%s: got %s want %s", v.Name, hexEncode(got), v.Digest)
		}
		passed++
	}
	return passed, nil
}

// hexEncode is a tiny hex encoder so this file does not pull in encoding/hex
// just for error messages; the vector comparison path is on the hot path of the
// test suite, not of the benchmark.
func hexEncode(b []byte) string {
	const digits = "0123456789abcdef"
	out := make([]byte, len(b)*2)
	for i, c := range b {
		out[2*i] = digits[c>>4]
		out[2*i+1] = digits[c&0x0f]
	}
	return string(out)
}

// SHA3DigestResult is the measured throughput for one SHA-3 variant.
type SHA3DigestResult struct {
	Variant    string  `json:"variant"`
	BlockSize  int     `json:"block_size"`
	MBps       float64 `json:"mbps"`
	Iterations int     `json:"iterations"`
	Backend    string  `json:"backend"`
	Digest     string  `json:"digest"`
	Error      string  `json:"error,omitempty"`
}

// BenchmarkSHA3 measures the pure-Go SHA-3 throughput for one variant.
func BenchmarkSHA3(v SHA3Variant, blockSize, iterations int) (SHA3DigestResult, error) {
	res := SHA3DigestResult{
		Variant:    v.String(),
		BlockSize:  blockSize,
		Iterations: iterations,
		Backend:    "pure-go",
	}
	mbps, err := BenchmarkHash(func() hash.Hash { return NewSHA3(v) }, blockSize, iterations)
	if err != nil {
		return res, err
	}
	res.MBps = mbps
	return res, nil
}

// SHA3Suite measures all four variants at one buffer size.
func SHA3Suite(blockSize, iterations int) []SHA3DigestResult {
	variants := []SHA3Variant{SHA3_224, SHA3_256, SHA3_384, SHA3_512}
	out := make([]SHA3DigestResult, 0, len(variants))
	for _, v := range variants {
		r, err := BenchmarkSHA3(v, blockSize, iterations)
		if err != nil {
			r.Error = err.Error()
		}
		out = append(out, r)
	}
	return out
}

// SHA3HardwareInfo reports whether the kernel exposes a CPACF-backed SHA-3
// driver and whether the AF_ALG interface can reach it.
type SHA3HardwareInfo struct {
	// KernelDriver is the /proc/crypto driver name, e.g. "sha3-256-s390".
	KernelDriver string `json:"kernel_driver"`
	// KernelPriority is that driver's priority. CPACF drivers register at 300.
	KernelPriority int `json:"kernel_priority"`
	// Hardware is true when the driver name ends in "-s390", which is the
	// naming convention every CPACF crypto module in the kernel follows.
	Hardware bool `json:"hardware"`
	// AFALGAvailable is true when a test hash through AF_ALG succeeded.
	AFALGAvailable bool   `json:"af_alg_available"`
	Error          string `json:"error,omitempty"`
}

// detectKernelCryptoFor reads /proc/crypto once and returns only the named
// algorithms, keyed by name.
//
// It is a thin wrapper over cpacf.DetectKernelCrypto so that the SHA-3 and ECC
// code paths do not each re-parse the file in their own dialect.
func detectKernelCryptoFor(names ...string) map[string]cpacf.KernelAlgorithm {
	report := cpacf.DetectKernelCrypto()
	out := make(map[string]cpacf.KernelAlgorithm, len(names))
	for _, n := range names {
		if alg, ok := report.Lookup(n); ok {
			out[n] = alg
		}
	}
	return out
}

// SHA3KernelInfo reads /proc/crypto for one variant and, when a driver is
// present, checks that AF_ALG can actually open a hash socket for it.
//
// The two checks answer different questions. /proc/crypto says "the kernel
// registered a CPACF driver at priority 300", which is what every in-kernel
// consumer (dm-crypt, kTLS, IPsec) will use. The AF_ALG probe says "userspace
// can reach that driver", which is what ZCrypt needs in order to measure it.
func SHA3KernelInfo(v SHA3Variant) SHA3HardwareInfo {
	info := SHA3HardwareInfo{}
	name := v.KernelName()
	if name == "" {
		info.Error = "unknown SHA-3 variant"
		return info
	}

	report := detectKernelCryptoFor(name)
	if alg, ok := report[name]; ok {
		info.KernelDriver = alg.Driver
		info.KernelPriority = alg.Priority
		info.Hardware = alg.Hardware
	} else {
		info.Error = "no driver registered for " + name
	}

	if info.Hardware {
		if err := probeAFALGHash(name); err != nil {
			info.Error = "AF_ALG probe: " + err.Error()
		} else {
			info.AFALGAvailable = true
		}
	}
	return info
}

// SHA3KernelDrivers returns the info for all four variants.
func SHA3KernelDrivers() []SHA3HardwareInfo {
	out := make([]SHA3HardwareInfo, 0, 4)
	for _, v := range []SHA3Variant{SHA3_224, SHA3_256, SHA3_384, SHA3_512} {
		out = append(out, SHA3KernelInfo(v))
	}
	return out
}

// ErrSHA3Unavailable is returned when the AF_ALG hardware path cannot be used.
var ErrSHA3Unavailable = errors.New("sha3: AF_ALG hardware path unavailable")

// SHA3HardwareBenchmark measures SHA-3 through AF_ALG, which on s390x reaches
// the KIMD-SHA3 function codes in the kernel's sha3-*-s390 driver.
//
// The comparison this enables is the point of the exercise: the same message
// hashed by the pure-Go sponge and by the CPACF hardware must produce the same
// digest, and the throughput difference is the hardware's contribution.
func SHA3HardwareBenchmark(v SHA3Variant, blockSize, iterations int) (SHA3DigestResult, error) {
	res := SHA3DigestResult{
		Variant:    v.String(),
		BlockSize:  blockSize,
		Iterations: iterations,
		Backend:    "af_alg",
	}
	if blockSize <= 0 || iterations <= 0 {
		return res, errors.New("sha3: block size and iterations must be positive")
	}

	h, err := newAFALGHash(v.KernelName())
	if err != nil {
		return res, err
	}
	defer h.Close()

	data := make([]byte, blockSize)
	for i := range data {
		data[i] = byte((i * 11) % 251)
	}

	t0 := time.Now()
	var digest []byte
	for i := 0; i < iterations; i++ {
		if err := h.Reset(); err != nil {
			return res, fmt.Errorf("sha3 af_alg: reset: %w", err)
		}
		if _, err := h.Write(data); err != nil {
			return res, fmt.Errorf("sha3 af_alg: write: %w", err)
		}
		digest, err = h.Sum()
		if err != nil {
			return res, fmt.Errorf("sha3 af_alg: read: %w", err)
		}
	}
	dur := time.Since(t0).Seconds()

	totalMB := float64(blockSize) * float64(iterations) / (1024 * 1024)
	res.MBps = totalMB / dur
	res.Digest = hexEncode(digest)
	return res, nil
}

// SHA3HardwareVerify hashes the same message through both paths and reports
// whether they agree. This is the correctness gate for the hardware path: a
// fast wrong answer is worse than a slow right one.
func SHA3HardwareVerify(v SHA3Variant, msg []byte) (bool, error) {
	soft := SHA3Sum(v, msg)

	h, err := newAFALGHash(v.KernelName())
	if err != nil {
		return false, err
	}
	defer h.Close()
	if _, err := h.Write(msg); err != nil {
		return false, err
	}
	hard, err := h.Sum()
	if err != nil {
		return false, err
	}
	return hexEncode(soft) == hexEncode(hard), nil
}
